import { db } from '../firebaseConfig';
import { doc, setDoc, serverTimestamp } from 'firebase/firestore';
import { generateSequentialPatientId } from './idGeneratorService';
import type{ PatientProfile } from '../patientData';

export async function createPatientWithAutoId(patientDetails: Partial<PatientProfile>) {
  const autoGeneratedId = await generateSequentialPatientId();
  const patientRef = doc(db, 'patients', autoGeneratedId);

  const newPatientData = {
    uid: autoGeneratedId,
    accountNo: autoGeneratedId,
    fullName: patientDetails.fullName || 'Mr./Mrs. New Patient',
    sex: patientDetails.sex || 'Not Specified',
    address: patientDetails.address || '123 Health Ave',
    contact: patientDetails.contact || '+1 (555) 000-0000',
    email: patientDetails.email || `${autoGeneratedId.toLowerCase()}@portal.com`,
    bloodType: patientDetails.bloodType || 'Unknown',
    allergies: patientDetails.allergies || 'None Recorded',
    emergencyContact: patientDetails.emergencyContact || 'Pending',
    insuranceProvider: patientDetails.insuranceProvider || 'Standard Coverage',
    assignedDoctor: {
      primaryDoctorName: 'Dr. Sarah Jenkins',
      specialty: 'Cardiologist / General Physician',
      location: 'Cardiovascular Care Unit - Room 4B'
    },
    createdAt: serverTimestamp(),
    updatedAt: serverTimestamp()
  };

  await setDoc(patientRef, newPatientData);

  return {
    success: true,
    patientId: autoGeneratedId,
    message: `Patient successfully registezred with ID: ${autoGeneratedId}`
  };
}